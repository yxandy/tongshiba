// ============ 最近使用表情 (localStorage) ============

const RECENT_EMOJIS_KEY = 'forum_recent_emojis'
const MAX_RECENT_EMOJIS = 7

/**
 * 获取最近使用的表情列表
 * @returns {Array} 表情对象数组
 */
export function getRecentEmojis() {
    try {
        const stored = localStorage.getItem(RECENT_EMOJIS_KEY)
        if (!stored) return []
        const ids = JSON.parse(stored)
        // 根据 ID 列表获取完整的表情对象
        return ids
            .map(id => emojiList.find(e => e.id === id))
            .filter(Boolean) // 过滤掉可能不存在的表情
    } catch {
        return []
    }
}

/**
 * 添加一个表情到最近使用列表
 * @param {Object} emoji 表情对象 { id, name, file }
 */
export function addRecentEmoji(emoji) {
    if (!emoji?.id) return

    try {
        const stored = localStorage.getItem(RECENT_EMOJIS_KEY)
        let ids = stored ? JSON.parse(stored) : []

        // 移除已存在的相同表情（如果有）
        ids = ids.filter(id => id !== emoji.id)

        // 添加到开头
        ids.unshift(emoji.id)

        // 限制最大数量
        if (ids.length > MAX_RECENT_EMOJIS) {
            ids = ids.slice(0, MAX_RECENT_EMOJIS)
        }

        localStorage.setItem(RECENT_EMOJIS_KEY, JSON.stringify(ids))
    } catch (e) {
        console.warn('Failed to save recent emoji:', e)
    }
}

